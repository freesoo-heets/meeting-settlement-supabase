create table if not exists public.jjinchin_feedback_bot_operators (
  kakao_uid text primary key check (length(kakao_uid) between 1 and 256),
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  assigned_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.jjinchin_feedback_reply_history (
  id uuid primary key default gen_random_uuid(),
  feedback_id uuid not null references public.jjinchin_feedback(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 4000),
  replied_by uuid not null references auth.users(id),
  source text not null check (source in ('web','kakao')),
  source_message_id text unique,
  replied_at timestamptz not null default now()
);
create index if not exists feedback_reply_history_lookup on public.jjinchin_feedback_reply_history(feedback_id,replied_at desc);

create table if not exists public.jjinchin_feedback_outbox (
  id uuid primary key default gen_random_uuid(),
  feedback_id uuid not null references public.jjinchin_feedback(id) on delete cascade,
  kind text not null check (kind in ('new','reminder')),
  state text not null default 'pending' check (state in ('pending','sending','sent','failed')),
  attempts integer not null default 0,
  due_at timestamptz not null default now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  unique(feedback_id,kind)
);
create index if not exists feedback_outbox_pending on public.jjinchin_feedback_outbox(state,due_at);

-- Queue only after BOTH content and real account identity have been written.
create or replace function public.jjinchin_feedback_enqueue_new()
returns trigger language plpgsql security definer set search_path = public as $$
begin
 insert into public.jjinchin_feedback_outbox(feedback_id,kind)
 values (new.feedback_id,'new') on conflict(feedback_id,kind) do nothing;
 return new;
end;
$$;
drop trigger if exists trg_jjinchin_feedback_enqueue_new on public.jjinchin_feedback_authors;
create trigger trg_jjinchin_feedback_enqueue_new
after insert on public.jjinchin_feedback_authors
for each row execute function public.jjinchin_feedback_enqueue_new();

-- Trigger from previously registered replies (web API); no overwrite of history.
create or replace function public.jjinchin_feedback_log_web_reply()
returns trigger language plpgsql security definer set search_path = public as $$
begin
 if (tg_op='INSERT' or new.content is distinct from old.content) then
   insert into public.jjinchin_feedback_reply_history(feedback_id,content,replied_by,source,replied_at)
   values(new.feedback_id,new.content,new.replied_by,'web',new.replied_at);
 end if;
 return new;
end;
$$;
drop trigger if exists trg_jjinchin_feedback_log_web_reply on public.jjinchin_feedback_replies;
create trigger trg_jjinchin_feedback_log_web_reply
after insert or update on public.jjinchin_feedback_replies
for each row execute function public.jjinchin_feedback_log_web_reply();

-- Service-role-only atomic claim to allow multiple bot workers safely.
create or replace function public.jjinchin_feedback_claim_outbox()
returns setof public.jjinchin_feedback_outbox language plpgsql security definer set search_path = public as $$
begin
 -- Only one reminder per case; queue after 24h, but only after notification sent.
 insert into public.jjinchin_feedback_outbox(feedback_id,kind,due_at)
 select f.id,'reminder', f.created_at + interval '24 hours'
 from public.jjinchin_feedback f
 join public.jjinchin_feedback_outbox n on n.feedback_id=f.id and n.kind='new' and n.state='sent'
 where f.status='received'
 and f.created_at < now()-interval '24 hours'
 on conflict(feedback_id,kind) do nothing;

 -- Reclaim expired leases after crash. Duplicate Kakao messages can occur if the send
 -- succeeded but acknowledgment was lost; label each message with stable outbox ID.
 update public.jjinchin_feedback_outbox set state='pending',due_at=now()
 where state='sending' and claimed_at < now()-interval '3 minutes';

 return query
 with candidates as (
  select id from public.jjinchin_feedback_outbox
  where state='pending' and due_at<=now()
  order by due_at,id for update skip locked limit 5
 ), taken as (
  update public.jjinchin_feedback_outbox q
  set state='sending', attempts=q.attempts+1, claimed_at=now()
  from candidates c where q.id=c.id returning q.*
 ) select * from taken;
end;
$$;

create or replace function public.jjinchin_feedback_ack_outbox(
 p_id uuid, p_success boolean, p_error text default null
) returns boolean language plpgsql security definer set search_path=public as $$
declare changed integer;
begin
 update public.jjinchin_feedback_outbox set
   state=case when p_success then 'sent'
     when attempts>=5 then 'failed' else 'pending' end,
   sent_at=case when p_success then now() else sent_at end,
   due_at=case when p_success then due_at else now()+(interval '1 minute' * least(60, power(2,greatest(attempts-1,0))::integer)) end,
   claimed_at=null, last_error=case when p_success then null else left(coalesce(p_error,'unknown'),300) end
 where id=p_id and state='sending';
 get diagnostics changed=row_count;
 return changed=1;
end;
$$;

-- Atomic, idempotent command execution. The operator maps to a verified site profile,
-- not a displayed Kakao nickname.
create or replace function public.jjinchin_feedback_bot_reply(
 p_kakao_uid text,p_receipt bigint,p_message_id text,p_content text
) returns text language plpgsql security definer set search_path=public as $$
declare actor uuid; fid uuid; added uuid;
begin
 if length(trim(p_content)) not between 1 and 4000 then return 'INVALID_CONTENT'; end if;
 if length(p_message_id) not between 1 and 256 then return 'INVALID_MESSAGE_ID'; end if;

 select o.profile_id into actor
 from public.jjinchin_feedback_bot_operators o
 join public.profiles p on p.id=o.profile_id
 where o.kakao_uid=p_kakao_uid
 and (p.role='owner' or (p.role='admin' and exists(
   select 1 from public.jjinchin_feedback_reviewers r where r.user_id=p.id)));
 if actor is null then return 'FORBIDDEN'; end if;

 -- Serialize against concurrent bot replies on the same ticket.
 select id into fid from public.jjinchin_feedback where receipt_no=p_receipt for update;
 if fid is null then return 'NOT_FOUND'; end if;
 if exists(select 1 from public.jjinchin_feedback_reply_history where source_message_id=p_message_id) then return 'ALREADY_PROCESSED'; end if;

 insert into public.jjinchin_feedback_reply_history(feedback_id,content,replied_by,source,source_message_id)
 values(fid,trim(p_content),actor,'kakao',p_message_id)
 on conflict(source_message_id) do nothing returning id into added;
 if added is null then return 'ALREADY_PROCESSED'; end if;

 -- Avoid duplicate web history trigger by writing latest reply directly inside this RPC.
 -- For bot replies, latest snapshot is updated WITHOUT a duplicate history event via
 -- separate trigger condition (web trigger skips rows with matching source history).
 insert into public.jjinchin_feedback_replies(feedback_id,content,replied_by,replied_at)
 values(fid,trim(p_content),actor,now())
 on conflict(feedback_id) do update set content=excluded.content,replied_by=excluded.replied_by,replied_at=excluded.replied_at;
 update public.jjinchin_feedback set status='answered',updated_at=now() where id=fid;
 return 'SAVED';
end;
$$;

-- Skip history logging if a matching bot event already exists in this transaction.
create or replace function public.jjinchin_feedback_log_web_reply()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 if (tg_op='INSERT' or new.content is distinct from old.content) and not exists(
   select 1 from public.jjinchin_feedback_reply_history h
   where h.feedback_id=new.feedback_id and h.source='kakao' and h.content=new.content
    and h.replied_by=new.replied_by and h.replied_at > now()-interval '10 seconds'
 ) then
   insert into public.jjinchin_feedback_reply_history(feedback_id,content,replied_by,source,replied_at)
   values(new.feedback_id,new.content,new.replied_by,'web',new.replied_at);
 end if;
 return new;
end;
$$;

