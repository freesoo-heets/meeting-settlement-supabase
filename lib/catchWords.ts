export const CATCH_WORDS: string[] = Array.from(new Set(WORDS.split(/\s+/).filter(Boolean)));

export function pickWord(used: string[]): string {
  const pool = CATCH_WORDS.filter((word) => !used.includes(word));
  const list = pool.length > 0 ? pool : CATCH_WORDS;
  return list[Math.floor(Math.random() * list.length)];
}

export function hintOf(word: string) {
  return `${"○".repeat(word.length)} (${word.length}글자)`;
}

export function normalizeGuess(text: string) {
  return text.replace(/\s+/g, "").toLowerCase();
}
